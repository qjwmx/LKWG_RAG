# --------------------------------------------------------------------------- 名称归一

# 精灵有形态后缀：「化蝶（平常的样子）」「卡瓦重（沙地附近的样子）」。
# 图鉴里这些是**同一只精灵的不同形态**，但阵容里可能写成带后缀的形式。
# 归一化后用于反查：先精确匹配，匹配不到再去掉括号重试。
_FORM_SUFFIX = re.compile(r"[（(][^)）]*[)）]")


def normalize_pet_name(name: str) -> str:
    """把带形态后缀的精灵名归一成基础名。

    「化蝶（平常的样子）」-> 「化蝶」
    没有括号时原样返回（已 strip）。
    """
    cleaned = (name or "").strip()
    if not cleaned:
        return ""
    return _FORM_SUFFIX.sub("", cleaned).strip() or cleaned


def split_form(name: str) -> tuple[str, str]:
    """拆出 (基础名, 形态描述)。无形态时形态为空串。"""
    cleaned = (name or "").strip()
    match = _FORM_SUFFIX.search(cleaned)
    if not match:
        return cleaned, ""
    return normalize_pet_name(cleaned), match.group(0).strip("（）()")


